#!/bin/bash

FILENAME_INIT_STRUCT="initial_structure.xyz"
BASEOUTDIR="out/"

FILENAME_MSM_PARAMS="msm_params.json"
TIMESTEP_FS=1.0
LOGINTERVAL_FS=500.0
PRESSURE_GPA=0.27127106227106224
ENSEMBLE="NPT"

N_TEMPS=30
RANGE_OF_TEMPS=(395.955 423.6806896551724 451.40637931034485 479.13206896551725 506.85775862068965 534.5834482758621 562.3091379310345 590.0348275862069 617.7605172413794 645.4862068965517 673.2118965517241 700.9375862068966 728.663275862069 756.3889655172413 784.1146551724139 811.8403448275863 839.5660344827586 867.291724137931 895.0174137931035 922.7431034482759 950.4687931034482 978.1944827586208 1005.9201724137931 1033.6458620689655 1061.371551724138 1089.0972413793104 1116.8229310344827 1144.5486206896553 1172.2743103448277 1200.0)
SIMTIME_PS_PER_SEGMENT=100.0

INPUTFILE="${FILENAME_INIT_STRUCT}"
SEGMENTDIR="${BASEOUTDIR}/0/"

for ((i=0;i<N_TEMPS;i++)); do
    CURRENT_TEMP="${RANGE_OF_TEMPS[$i]}"

    echo "- Running temperature segment ${i} out of $((N_TEMPS-1))"
    echo "- T = ${CURRENT_TEMP} K"
    echo "- Reading initial_structure from: ${INPUTFILE}"
    echo "- Writing output to:              ${SEGMENTDIR}"

    python run_md_ase.py \
        --inputstruct $INPUTFILE \
        --msm_params $FILENAME_MSM_PARAMS \
        --outdir $SEGMENTDIR \
        --timestep_fs $TIMESTEP_FS \
        --loginterval_fs $LOGINTERVAL_FS \
        --simtime_ps $SIMTIME_PS_PER_SEGMENT \
        --ensemble $ENSEMBLE \
        --temp_K $CURRENT_TEMP \
        --pressure_GPa $PRESSURE_GPA

    INPUTFILE="${SEGMENTDIR}/md.traj"
    SEGMENTDIR="${BASEOUTDIR}/$((i+1))/"

    echo
done
